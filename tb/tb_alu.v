`timescale 1ns/1ps

module tb_alu;

    // Inputs to ALU
    reg [31:0] a;
    reg [31:0] b;
    reg [3:0]  alu_control;

    // Outputs from ALU
    wire [31:0] result;
    wire        zero;

    // Instantiate ALU
    alu dut (
        .a(a),
        .b(b),
        .alu_control(alu_control),
        .result(result),
        .zero(zero)
    );

    initial begin

        $monitor("Time=%0t | A=%h | B=%h | Control=%b | Result=%h | Zero=%b",
                 $time, a, b, alu_control, result, zero);

        // --------------------------------
        // TEST 1: ADD
        // 10 + 20 = 30
        // --------------------------------
        a = 32'd10;
        b = 32'd20;
        alu_control = 4'b0000;
        #10;


        // --------------------------------
        // TEST 2: SUB
        // 20 - 10 = 10
        // --------------------------------
        a = 32'd20;
        b = 32'd10;
        alu_control = 4'b0001;
        #10;


        // --------------------------------
        // TEST 3: SUB resulting in zero
        // 10 - 10 = 0
        // zero should become 1
        // --------------------------------
        a = 32'd10;
        b = 32'd10;
        alu_control = 4'b0001;
        #10;


        // --------------------------------
        // TEST 4: AND
        // --------------------------------
        a = 32'h0F0F0F0F;
        b = 32'h00FF00FF;
        alu_control = 4'b0010;
        #10;


        // --------------------------------
        // TEST 5: OR
        // --------------------------------
        a = 32'h0F0F0F0F;
        b = 32'h00FF00FF;
        alu_control = 4'b0011;
        #10;


        // --------------------------------
        // TEST 6: XOR
        // --------------------------------
        a = 32'h0F0F0F0F;
        b = 32'h00FF00FF;
        alu_control = 4'b0100;
        #10;


        // --------------------------------
        // TEST 7: SLT
        // 5 < 10 => 1
        // --------------------------------
        a = 32'd5;
        b = 32'd10;
        alu_control = 4'b0101;
        #10;


        // --------------------------------
        // TEST 8: SLT
        // 10 < 5 => 0
        // --------------------------------
        a = 32'd10;
        b = 32'd5;
        alu_control = 4'b0101;
        #10;


        // --------------------------------
        // TEST 9: SLT with negative number
        // -5 < 3 => 1
        // --------------------------------
        a = -32'sd5;
        b = 32'd3;
        alu_control = 4'b0101;
        #10;


        // --------------------------------
        // TEST 10: SLTU
        // 5 < 10 => 1
        // --------------------------------
        a = 32'd5;
        b = 32'd10;
        alu_control = 4'b1001;
        #10;


        // --------------------------------
        // TEST 11: SLL
        // 5 << 1 = 10
        // --------------------------------
        a = 32'd5;
        b = 32'd1;
        alu_control = 4'b0110;
        #10;


        // --------------------------------
        // TEST 12: SRL
        // 20 >> 2 = 5
        // --------------------------------
        a = 32'd20;
        b = 32'd2;
        alu_control = 4'b0111;
        #10;


        // --------------------------------
        // TEST 13: SRA positive
        // 20 >>> 2 = 5
        // --------------------------------
        a = 32'd20;
        b = 32'd2;
        alu_control = 4'b1000;
        #10;


        // --------------------------------
        // TEST 14: SRA negative
        // -20 >>> 2
        // --------------------------------
        a = -32'sd20;
        b = 32'd2;
        alu_control = 4'b1000;
        #10;


        $finish;

    end

endmodule