module instruction_memory (
    input  wire [31:0] address,
    output wire [31:0] instruction
);

    reg [31:0] memory [0:255];

    initial begin

        // =========================================
        // 1. ADDI
        // =========================================

        // x1 = 10
        // PC = 0
        memory[0] = 32'h00A00093;


        // =========================================
        // 2. ADDI
        // =========================================

        // x2 = 20
        // PC = 4
        memory[1] = 32'h01400113;


        // =========================================
        // 3. ADD
        // =========================================

        // x3 = x1 + x2 = 30
        // PC = 8
        memory[2] = 32'h002081B3;


        // =========================================
        // 4. SW
        // =========================================

        // memory[0] = x3 = 30
        // PC = 12
        memory[3] = 32'h00302023;


        // =========================================
        // 5. LW
        // =========================================

        // x4 = memory[0] = 30
        // PC = 16
        memory[4] = 32'h00002203;


        // =========================================
        // 6. BEQ
        // =========================================

        // x3 == x4
        // 30 == 30
        // Branch should be TAKEN
        //
        // PC = 20
        // Target = PC + 8 = 28
        memory[5] = 32'h00418463;


        // =========================================
        // 7. This should be SKIPPED
        // =========================================

        // x5 = 99
        // PC = 24
        memory[6] = 32'h06300293;


        // =========================================
        // 8. Branch target
        // =========================================

        // x5 = 42
        // PC = 28
        memory[7] = 32'h02A00293;


        // =========================================
        // 9. JAL
        // =========================================

        // x6 = PC + 4
        // Jump forward by 8 bytes
        //
        // PC = 32
        // Target = 40
        memory[8] = 32'h0080036F;


        // =========================================
        // 10. This should be SKIPPED
        // =========================================

        // x7 = 99
        // PC = 36
        memory[9] = 32'h06300393;


        // =========================================
        // 11. JAL target
        // =========================================

        // x7 = 7
        // PC = 40
        memory[10] = 32'h00700393;


        // =========================================
        // 12. NOP
        // =========================================

        // PC = 44
        memory[11] = 32'h00000013;

    end

    assign instruction = memory[address[31:2]];

endmodule